let n = 5 ;
switch (n) {
    case 1:
        console.log("The value is 1");
        break;
    case 2:
        console.log("The value is 2");
        break;
    case 3:
        console.log("The value is 3");
        break;
    case 4:
        console.log("The value is 4");
        break;
    case 5:
        console.log("The value is 5");
        break;
    default:
        console.log("The value is not between 1 and 5");
}